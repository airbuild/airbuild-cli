package setup

import (
	"fmt"
	"os"
	"path/filepath"
)

const rnTelemetryFilename = "airbuild-telemetry.js"

// rnTelemetryTemplate is a self-contained module the app imports once at
// startup. It reports launch outcomes to AirBuild so crash-rate
// auto-pause works for React Native — the Expo Updates protocol is
// pull-only and has no report-back channel of its own.
//
// Attribution:
//   - launch_success: the running update is a downloaded OTA update
//     (not the embedded bundle).
//   - emergency_launch: expo-updates recovered to the previous/embedded
//     bundle after a startup crash. The crashed update is the one we
//     persisted as "pending" when its download completed — expo-updates
//     doesn't expose the crashed update's id on the recovery launch.
const rnTelemetryTemplate = `// airbuild-telemetry.js — generated by ` + "`airbuild codepush react-native install`" + `.
// Reports OTA launch outcomes to AirBuild so crash-rate auto-pause works
// for React Native updates. Import once, as early as possible in your
// app entry file (App.js / index.js / app/_layout.tsx):
//
//   import './airbuild-telemetry';
//
// Safe to commit — it contains only your app's public distribution key
// (the same one already embedded in updates.url), no secrets. Telemetry
// failures are always swallowed and never affect app behavior.

import * as Updates from 'expo-updates';
import { Platform } from 'react-native';

const EVENTS_URL = %q;

const DEVICE_PARAM = 'airbuild-device-id';
const PENDING_PARAM = 'airbuild-pending-update';
// A crash during startup must not claim install success — only report
// launch_success after the bundle has survived a short settle window.
// If the app dies inside the window the pending marker stays set, so the
// next boot's emergency_launch still attributes the crash correctly.
const SETTLE_DELAY_MS = 5000;

function uuid() {
  return 'xxxxxxxx-xxxx-4xxx-yxxx-xxxxxxxxxxxx'.replace(/[xy]/g, (c) => {
    const r = (Math.random() * 16) | 0;
    return (c === 'x' ? r : (r & 0x3) | 0x8).toString(16);
  });
}

// Debug snapshot — readable from JS as globalThis.__airbuildTelemetry.
globalThis.__airbuildTelemetry = { events: [] };
function dbg(entry) {
  try {
    globalThis.__airbuildTelemetry.events.push(entry);
  } catch {}
}

async function post(payload) {
  try {
    const res = await fetch(EVENTS_URL, {
      method: 'POST',
      headers: { 'Content-Type': 'application/json' },
      body: JSON.stringify(payload),
    });
    dbg({ ...payload, status: res.status });
  } catch (e) {
    dbg({ ...payload, status: 'error', error: String(e) });
    // Telemetry must never affect app behavior.
  }
}

// Track the most recently downloaded update. When it launches on the
// next restart it either reports launch_success (updateId matches) or —
// if it crashed during startup — emergency_launch attributes the failure
// to this id.
try {
  Updates.addUpdatesStateChangeListener?.((event) => {
    try {
      const manifest = event && event.context && event.context.downloadedManifest;
      if (manifest && manifest.id) {
        Updates.setExtraParamAsync(PENDING_PARAM, manifest.id).catch(() => {});
      }
    } catch {}
  });
} catch {}

(async () => {
  if (!Updates.isEnabled) return;
  try {
    let params = {};
    try {
      params = (await Updates.getExtraParamsAsync()) || {};
    } catch {}

    let deviceId = params[DEVICE_PARAM];
    if (!deviceId) {
      deviceId = uuid();
      Updates.setExtraParamAsync(DEVICE_PARAM, deviceId).catch(() => {});
    }

    const pending = params[PENDING_PARAM] || null;
    const platform = Platform.OS === 'ios' ? 'ios' : Platform.OS === 'android' ? 'android' : undefined;
    dbg({
      boot: true,
      deviceId,
      pending,
      updateId: Updates.updateId,
      isEmbeddedLaunch: Updates.isEmbeddedLaunch,
      isEmergencyLaunch: Updates.isEmergencyLaunch,
      isEnabled: Updates.isEnabled,
    });

    if (Updates.isEmergencyLaunch) {
      // The previously-launched update crashed during startup; the
      // running bundle is the recovered fallback, so updateId here is
      // NOT the crashed update — attribute via the persisted pending id
      // (or let the server fall back to the device's last checkin).
      await post({
        event: 'emergency_launch',
        deviceId,
        updateId: pending || undefined,
        reason: Updates.emergencyLaunchReason || undefined,
        platform,
      });
      if (pending) Updates.setExtraParamAsync(PENDING_PARAM, null).catch(() => {});
      return;
    }

    if (pending && pending !== Updates.updateId) {
      // A downloaded update was skipped entirely — we booted into a
      // different bundle (embedded or an older update). That means it
      // either crashed so early the process died before error recovery
      // could flag isEmergencyLaunch, or the channel rolled back.
      // A fresh check tells them apart: a rollBackToEmbedded directive
      // is benign; anything else means the pending update failed.
      try {
        const check = await Updates.checkForUpdateAsync();
        if (check && check.isRollBackToEmbedded) {
          Updates.setExtraParamAsync(PENDING_PARAM, null).catch(() => {});
        } else {
          await post({
            event: 'emergency_launch',
            deviceId,
            updateId: pending,
            reason: Updates.emergencyLaunchReason || 'pending_update_never_launched',
            platform,
          });
          Updates.setExtraParamAsync(PENDING_PARAM, null).catch(() => {});
        }
      } catch {
        // Check failed (e.g. offline) — keep the pending marker and
        // retry on the next boot.
      }
    }

    if (!Updates.isEmbeddedLaunch && Updates.updateId) {
      // Running a downloaded OTA update — report success only once the
      // bundle has survived the settle window.
      const runningUpdateId = Updates.updateId;
      setTimeout(() => {
        post({
          event: 'launch_success',
          deviceId,
          updateId: runningUpdateId,
          platform,
        });
        if (pending === runningUpdateId) {
          Updates.setExtraParamAsync(PENDING_PARAM, null).catch(() => {});
        }
      }, SETTLE_DELAY_MS);
      return;
    }
  } catch {}
})();
`

var rnEntryCandidates = []string{
	"App.js", "App.jsx", "App.ts", "App.tsx",
	"index.js", "index.ts", "index.tsx",
	"app/_layout.js", "app/_layout.ts", "app/_layout.tsx",
	"src/App.js", "src/App.jsx", "src/App.ts", "src/App.tsx",
	"src/app/_layout.js", "src/app/_layout.ts", "src/app/_layout.tsx",
}

func rnTelemetryPath() string {
	return filepath.Join(".", rnTelemetryFilename)
}

func checkTelemetry() CheckResult {
	if !FileExists(rnTelemetryPath()) {
		return Warn("telemetry module", "airbuild-telemetry.js not found",
			"Run `airbuild codepush react-native install` to generate it")
	}
	for _, entry := range rnEntryCandidates {
		if FileContains(entry, "airbuild-telemetry") {
			return Pass("telemetry module", "airbuild-telemetry.js generated and imported")
		}
	}
	return Warn("telemetry module",
		"airbuild-telemetry.js exists but no entry file imports it",
		`Add "import './airbuild-telemetry';" to your app entry (App.js / index.js / app/_layout.tsx)`)
}

func writeTelemetry() error {
	dk, err := distributionKey()
	if err != nil {
		return err
	}
	eventsURL := apiURL() + "/api/codepush/react-native/events?key=" + dk
	content := fmt.Sprintf(rnTelemetryTemplate, eventsURL)
	if FileExists(rnTelemetryPath()) {
		existing, err := os.ReadFile(rnTelemetryPath())
		if err == nil && string(existing) == content {
			return nil
		}
	}
	if err := os.WriteFile(rnTelemetryPath(), []byte(content), 0644); err != nil {
		return fmt.Errorf("could not write %s: %w", rnTelemetryFilename, err)
	}
	return nil
}
