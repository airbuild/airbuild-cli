package cmd

import (
	"fmt"
	"strings"

	"github.com/airbuild/airbuild-cli/internal/agents"
	"github.com/airbuild/airbuild-cli/internal/config"
	"github.com/airbuild/airbuild-cli/internal/ui"
	"github.com/spf13/cobra"
)

// serverBase returns the configured AirBuild origin (env/config), falling
// back to the hosted default. Never fails — guides work before login.
func serverBase() string {
	if cfg, err := config.Load(); err == nil && cfg.APIURL != "" {
		return cfg.APIURL
	}
	return agents.DefaultServer
}

var guideCmd = &cobra.Command{
	Use:   "guide [topic]",
	Short: "Print a runbook for AI agents and humans (generated by this CLI version)",
	Long: `Print a task runbook. The text is embedded in this CLI binary, so it always
matches the installed version — unlike copies stored in a project.

Topics:
  distribution   Upload builds, install links/QR, iOS UDIDs, in-app SDKs, CI, webhooks
  codepush       OTA shared rules: patch vs new binary, lifecycle, channels, rollout
  flutter        Flutter CodePush runbook (Android + iOS)
  react-native   React Native CodePush runbook (Expo Updates, Android + iOS)

Examples:
  airbuild guide                  # list topics
  airbuild guide codepush
  airbuild guide flutter --json   # {"topic","version","content"}`,
	Args: cobra.MaximumNArgs(1),
	RunE: func(cmd *cobra.Command, args []string) error {
		if len(args) == 0 {
			if jsonOutput {
				type entry struct {
					Topic   string `json:"topic"`
					Summary string `json:"summary"`
				}
				list := make([]entry, 0, len(agents.Topics))
				for _, t := range agents.Topics {
					list = append(list, entry{t.Name, t.Summary})
				}
				ui.PrintJSON(list)
				return nil
			}
			for _, t := range agents.Topics {
				fmt.Printf("%-14s %s\n", t.Name, t.Summary)
			}
			return nil
		}

		text, ok := agents.Guide(args[0], serverBase())
		if !ok {
			names := make([]string, 0, len(agents.Topics))
			for _, t := range agents.Topics {
				names = append(names, t.Name)
			}
			return failf("Unknown topic %q. Available: %s", args[0], strings.Join(names, ", "))
		}
		if jsonOutput {
			ui.PrintJSON(map[string]string{"topic": args[0], "version": cliVersion, "content": text})
			return nil
		}
		fmt.Print(text)
		return nil
	},
}

func init() {
	rootCmd.AddCommand(guideCmd)
}
